/**
 * 加入团队弹窗：支持“邀请码加入”与“申请加入（填写团队 ID 与留言）”两种方式。
 *
 * 接口根据团队加入方式返回 joined（已加入）或 pending（已提交申请）：
 * 前者提示加入成功，后者提示等待管理员审批；两种结果都通知父级刷新列表。
 */

import { useEffect, useState } from 'react'

import { joinTeam } from '../../api/teamApi'
import { useToast } from '../../context/ToastContext'
import { getErrorMessage } from '../../hooks/errorMessage'
import Button from '../ui/Button'
import Input from '../ui/Input'
import Modal from '../ui/Modal'
import RadioGroup from '../ui/RadioGroup'
import Textarea from '../ui/Textarea'
import styles from './JoinTeamDialog.module.css'

/** 加入方式：邀请码 / 申请。 */
type JoinMode = 'invite' | 'apply'

/** 加入方式选项。 */
const JOIN_MODE_OPTIONS = [
  { value: 'invite', label: 'Invite Code', description: 'Use an invite code generated by a team admin.' },
  { value: 'apply', label: 'Apply to Join', description: 'Enter the team ID and a message, then wait for approval.' },
]

/** JoinTeamDialog 组件属性。 */
export interface JoinTeamDialogProps {
  /** 弹窗是否打开。 */
  open: boolean
  /** 关闭回调。 */
  onClose: () => void
  /** 加入成功或申请提交成功回调（用于刷新团队列表）。 */
  onJoined: () => void
}

/** 加入团队弹窗。 */
export default function JoinTeamDialog({ open, onClose, onJoined }: JoinTeamDialogProps) {
  const { showToast } = useToast()
  const [joinMode, setJoinMode] = useState<JoinMode>('invite')
  const [inviteCode, setInviteCode] = useState<string>('')
  const [teamId, setTeamId] = useState<string>('')
  const [message, setMessage] = useState<string>('')
  const [formError, setFormError] = useState<string | undefined>(undefined)
  const [submitting, setSubmitting] = useState<boolean>(false)

  /** 每次打开时重置表单。 */
  useEffect(() => {
    if (!open) {
      return
    }
    setJoinMode('invite')
    setInviteCode('')
    setTeamId('')
    setMessage('')
    setFormError(undefined)
  }, [open])

  /** 提交加入请求。 */
  const handleSubmit = async (): Promise<void> => {
    if (joinMode === 'invite' && inviteCode.trim() === '') {
      setFormError('Enter an invite code.')
      return
    }
    if (joinMode === 'apply') {
      const parsedTeamId = Number(teamId)
      if (!Number.isInteger(parsedTeamId) || parsedTeamId <= 0) {
        setFormError('Enter a valid team ID.')
        return
      }
    }
    setSubmitting(true)
    try {
      const joinResult = await joinTeam(
        joinMode === 'invite'
          ? { inviteCode: inviteCode.trim() }
          : { teamId: Number(teamId), message: message.trim() === '' ? undefined : message.trim() },
      )
      if (joinResult.status === 'pending') {
        showToast('Join request submitted. Waiting for team admin approval.', 'success')
      } else {
        showToast('Joined team: ' + joinResult.teamName, 'success')
      }
      onJoined()
      onClose()
    } catch (caughtError: unknown) {
      showToast(getErrorMessage(caughtError, 'Failed to join team. Check the invite code or request details.'), 'error')
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <Modal
      open={open}
      title="Join Team"
      size="medium"
      onClose={() => {
        if (!submitting) {
          onClose()
        }
      }}
      footer={
        <div className={styles.footer}>
          <Button variant="secondary" onClick={onClose} disabled={submitting}>
            Cancel
          </Button>
          <Button onClick={handleSubmit} loading={submitting}>
            {joinMode === 'invite' ? 'Join Team' : 'Submit Request'}
          </Button>
        </div>
      }
    >
      <div className={styles.formBody}>
        <RadioGroup<JoinMode>
          value={joinMode}
          onChange={(nextMode) => {
            setJoinMode(nextMode)
            setFormError(undefined)
          }}
          options={JOIN_MODE_OPTIONS}
          disabled={submitting}
        />
        {joinMode === 'invite' ? (
          <Input
            label="Invite Code *"
            value={inviteCode}
            onChange={(event) => setInviteCode(event.target.value)}
            placeholder="Enter the invite code provided by a team admin."
            error={formError}
            maxLength={32}
            disabled={submitting}
          />
        ) : (
          <>
            <Input
              label="Team ID *"
              value={teamId}
              onChange={(event) => setTeamId(event.target.value)}
              placeholder="Enter the numeric team ID to join."
              error={formError}
              disabled={submitting}
            />
            <Textarea
              label="Request Message"
              value={message}
              onChange={(event) => setMessage(event.target.value)}
              placeholder="Briefly explain why you want to join."
              rows={3}
              maxLength={255}
              disabled={submitting}
            />
          </>
        )}
        <p className={styles.hint}>
          Invite code mode requires a code. In approval mode, a team admin must approve your request before you can join.
        </p>
      </div>
    </Modal>
  )
}
